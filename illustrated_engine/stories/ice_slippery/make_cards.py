def main() -> int:
    """Delegate plate generation to the V13 generator (single pixel source)."""
    import runpy
    sys.path.insert(0, str(HERE))
    runpy.run_path(str(HERE / "make_plates.py"), run_name="__main__")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
