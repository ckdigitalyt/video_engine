#!/usr/bin/env python3
"""ice_slippery V13 card manifest — realigned to the 6-beat visual plan.

V13 plates are generated by make_plates.py (deterministic ink-wash cards,
no baked-in text). This file no longer draws a parallel V6 card set: its
job is the plate-element manifest the planner parses (engine.planv5.
_plate_manifest) — per-asset label anchors at TRUE plate-feature
coordinates, feeding hero recognizability, planv8 state choreography
(REVEAL/ISOLATE/FLOW/CONSEQUENCE rects) and the v9 contradiction/payoff
localization.

Coordinate convention: the manifest parser reads positions as fractions of
a 1536x1024 stage (cx/1536, cy/1024). The V13 plates are 2160x3840, so
every coordinate below is plate_px * (1536/2160, 1024/3840) — i.e.
(x*0.71111, y*0.26667) — taken from the card_bN() geometry in
make_plates.py. Running this script delegates to make_plates.py so the
committed plate set stays the single source of pixels.
"""
